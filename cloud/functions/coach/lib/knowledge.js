/** 按关键词命中，把相关「知识卡」文本拼进上下文（不引向量库）。 */
function routeKnowledge(messages) {
  if (!CARDS.length) { return ''; }
  var users = (messages || []).filter(function (m) { return m && m.role === 'user'; })
    .map(function (m) { return m.content || ''; });
  var text = users.slice(-KNOW_LOOKBACK).join('\n');
  if (!text) { return ''; }
  var scored = [];
  CARDS.forEach(function (c) {
    var hits = 0;
    c.keywords.forEach(function (kw) { if (kw && text.indexOf(kw) >= 0) { hits++; } });
    if (hits) { scored.push({ hits: hits, card: c }); }
  });
  if (!scored.length) { return ''; }
  scored.sort(function (a, b) { return b.hits - a.hits; });
  var picked = [];
  var total = 0;
  scored.slice(0, KNOW_MAX_CARDS).forEach(function (s) {
    var block = '### ' + (s.card.title || '知识卡') + '\n' + s.card.body;
    if (picked.length && total + block.length > KNOW_MAX_CHARS) { return; }
    picked.push(block);
    total += block.length;
  });
  if (!picked.length) { return ''; }
  return ('\n\n【已核验知识参考（自撰/整理，仅供一般性参考；健康内容非医疗诊断，回答健康话题务必提示「仅供参考」）】\n'
    + picked.join('\n\n'));
}

module.exports = { routeKnowledge: routeKnowledge };
